"""Write the deliverable spec from the complete probed route inventory.

Inputs: spec/routes_full.json (every registration at v1.5.0, live-probed),
        OpenTodo/docs/openapi.json (schemas, summaries, examples).
Outputs: spec/API.md, spec/OTDA.openapi.json
"""
import json
from collections import defaultdict
from pathlib import Path

SPEC = Path(r"W:\repos\OTDA\spec")
DOC = Path(r"W:\repos\OTDA\_research\OpenTodo\docs\openapi.json")
AI_TAG = {"In-app assistant", "AI assistants (MCP)", "Routines",
          "Keeping a project away from assistants"}
AI_PATH = ("/assistant", "/mcp", "/relay/", "/routines/", "/agent-access",
           "/me/oauth-grants", "/routine-emails", "/oauth/")


def is_ai(path, tags):
    return bool(AI_TAG & set(tags)) or any(p in path for p in AI_PATH)


def main():
    routes = json.loads((SPEC / "routes_full.json").read_text(encoding="utf-8"))["routes"]
    doc = json.loads(DOC.read_text(encoding="utf-8"))
    meta = {}
    for path, item in doc["paths"].items():
        for method, op in item.items():
            meta[(method.upper(), path)] = op

    rows, ai_rows, host_rows, absent_rows = [], [], [], []
    for r in routes:
        op = meta.get((r["method"], r["path"]), {})
        tags = op.get("tags") or []
        row = dict(r, tags=tags, summary=op.get("summary", ""),
                   policy_api=op.get("x-opentodo-policy", ""), in_openapi=bool(op))
        if r["host_only"]:
            host_rows.append(row)
        elif not r.get("exists", True):
            absent_rows.append(row)
        elif is_ai(r["path"], tags):
            ai_rows.append(row)
        else:
            rows.append(row)

    # filtered OpenAPI: only confirmed, non-AI operations, keeping full schemas
    out = json.loads(json.dumps(doc))
    keep = {}
    for r in rows:
        if not r["in_openapi"]:
            continue
        keep.setdefault(r["path"], {})
        m = r["method"].lower()
        keep[r["path"]][m] = doc["paths"][r["path"]][m]
    out["paths"] = keep
    out["info"]["title"] = "OTDA — OpenTodo server API (confirmed on v1.5.0)"
    out["info"]["version"] = "v1.5.0"
    out["info"]["description"] = (
        "OpenTodo's own OpenAPI description, filtered to the operations this implementation "
        "uses and to those the v1.5.0 server actually serves. Every path was probed live; "
        "operations the server answered 404 for, and the AI surface, were removed. "
        "Generated by spec/make_spec.py — do not edit by hand.")
    (SPEC / "OTDA.openapi.json").write_text(json.dumps(out, indent=1), encoding="utf-8")

    by_area = defaultdict(list)
    for r in rows:
        plain = [t for t in r["tags"] if t not in AI_TAG]
        area = {"Agent tokens": "Tasks, projects and other synced data"}.get(plain[0], plain[0]) if plain else "Other routes (not in the OpenAPI description)"
        by_area[area].append(r)
    for v in by_area.values():
        v.sort(key=lambda r: (r["path"], r["method"]))

    api = [r for r in rows if r["path"].startswith("/api/v1/")]
    other = [r for r in rows if not r["path"].startswith("/api/v1/")]

    L = []
    a = L.append
    a("# OTDA — confirmed OpenTodo API spec\n")
    a(f"Server: `https://otd.003274.xyz` — **v1.5.0**. "
      f"**{len(api)} `/api/v1` operations**, all present on the live server except the two listed "
      f"below; **{len(other)} other routes**; **{len(ai_rows)} AI operations excluded by request**.\n")
    a("Regenerate all of it with:\n")
    a("```powershell\n"
      "$py spec/build_routes_full.py    # parse every registration at tag v1.5.0 + probe live\n"
      "$py spec/probe_openapi.py        # probe the repo's OpenAPI description, capture samples\n"
      "$py spec/make_spec.py            # write API.md + OTDA.openapi.json\n"
      "```\n")
    a("## How it was established (nothing assumed)\n")
    a("| Evidence | Role |")
    a("| --- | --- |")
    a("| `OpenTodo` @ tag `v1.5.0` — every `mux.handle` / `mux.Handle` registration, incl. the route "
      "packages (`maproutes`, `speech`, `davroutes`) and the generic `/api/v1/{collection}` patterns "
      "expanded over the 12 collection names | the complete route list |")
    a("| Live `OPTIONS` probe of every path (405 + `Allow` = exists, 404 = absent) | proves what this "
      "server serves |")
    a("| `OpenTodo/docs/openapi.json` (the file behind <https://open-todo.app/docs/api/>) | schemas, "
      "request/response bodies, examples, policy |")
    a("| `GET`s of the collections | real payload shapes in `spec/samples.json` |")
    a("")
    absent_notes = {"POST /api/v1/demo/sandbox": "demo instances only",
                    "GET /api/v1/export/archive": "host mode only"}
    a("Absent on this server — do not call: " + ", ".join(
        f"`{r['method']} {r['path']}` ({absent_notes.get(r['method'] + ' ' + r['path'], 'not served')})"
        for r in absent_rows) + ".\n")
    a("> `GET /api/v1/openapi.json` does **not** exist before a later release — it answers 404 here. "
      "The spec in the repository is generated from `main`, so it lists operations this server does "
      "not have; that is why every route above was probed instead of trusted.\n")
    a("## Auth\n")
    a("- Bearer token on every call: `Authorization: Bearer ot_…`. Never follow a redirect with it attached.")
    a("- `full` tokens reach everything except *credential* routes (tokens, passkeys, 2FA, user admin, "
      "secret-bearing settings); those need `admin` or a session. The `Token?` column says which.")
    a("- Email + password without an existing token: `POST /api/v1/auth/login` (session cookie) → "
      "`POST /api/v1/tokens` → `POST /api/v1/auth/logout`; keep the returned `secret`. Send no `Origin` "
      "header and a JSON body on the token call.")
    a("- Do **not** use `/app/sign-in` + `POST /api/v1/app/token`: that flow exists for the official app "
      "(scope `app`, fixed `opentodo://signed-in` redirect).")
    a("- `read` tokens may only `GET`; `agent` tokens are the AI surface and are excluded here.\n")
    a("## Errors\n")
    a('`{"error":{"code","message"}}` on every failure. Branch on `code`. A known path with a wrong '
      "method answers 405 + `Allow`; an unknown path answers 404 `not_found`; `401` means re-authenticate, "
      "`403 insufficient_scope` means the token is too narrow.\n")
    a("## Sync is the data path\n")
    a("`POST /api/v1/sync` — one endpoint that carries the whole replicated state: push queued ops, pull "
      "everything after `cursor`. Field-level last-writer-wins on `(ts, device)`; 1000 ops / ~4 MB per "
      "page (`hasMore`); `generation` changes only when the server is restored from a backup; `rejected[]` "
      "answers per-op verdicts and carries the server's value for refused fields; `purged[]` names entities "
      "to delete locally. Live wake-up: `GET /api/v1/sync/events?device=…` (SSE, `event: ops` carries only "
      "a cursor). Full contract: `OpenTodo/docs/sync.md`.\n")
    a("## Endpoints\n")
    a("`Token?` = callable with a bearer token (`no` = session-only or credential route). "
      "`Confirmed` = answered the live probe.\n")
    for area in sorted(by_area, key=lambda t: (-len(by_area[t]), t)):
        a(f"### {area} ({len(by_area[area])})\n")
        a("| Method | Path | Summary | Policy | Token? | Confirmed |")
        a("| --- | --- | --- | --- | --- | --- |")
        for r in by_area[area]:
            policy = r["policy_api"] or r["policy"]
            token_ok = "no" if ("session-only" in policy or "credential" in policy) else "yes"
            a(f"| {r['method']} | `{r['path']}` | {r['summary']} | {policy} | {token_ok} | yes |")
        a("")
    a("## Excluded: the AI surface\n")
    a(f"{len(ai_rows)} operations were removed on purpose:" if ai_rows else "None.")
    seen = set()
    for r in sorted(ai_rows, key=lambda r: r["path"]):
        if r["path"] in seen:
            continue
        seen.add(r["path"])
        a(f"- `{r['path']}`")
    a("")
    if host_rows:
        a("## Not on a self-hosted server\n")
        a("`/operator/v1/*` exists only when the binary runs in host mode (`OPENTODO_HOST_URL`) — "
          "an operator surface, not part of the app's world.")
        a("")
    (SPEC / "API.md").write_text("\n".join(L), encoding="utf-8")
    print(f"API.md: {len(rows)} ops in {len(by_area)} areas "
          f"({len(api)} api, {len(other)} non-api); excluded {len(ai_rows)} ai, {len(host_rows)} host")
    print(f"OTDA.openapi.json: {len(keep)} paths")


if __name__ == "__main__":
    main()
